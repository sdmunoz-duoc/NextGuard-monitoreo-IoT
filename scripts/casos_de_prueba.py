def casos():
    out = []
    for (cid, titulo, req, prio, tipo, pre, pasos, datos, esperado, auto) in _CASOS:
        cod = cid.split("-")[1]
        nivel, nombre_nivel = NIVELES[cod]
        out.append({
            "id": cid, "nivel": nivel, "componente": nombre_nivel, "titulo": titulo, "requisito": req,
            "prioridad": prio, "tipo": tipo, "precondiciones": pre,
            "pasos": "\n".join(f"{i}. {p}" for i, p in enumerate(pasos, 1)),
            "datos": datos, "esperado": esperado, "automatizacion": auto,
            "resultado_real": "", "estado": "Pendiente", "fecha": "", "ejecutor": "", "evidencia": "",
        })
    return out


